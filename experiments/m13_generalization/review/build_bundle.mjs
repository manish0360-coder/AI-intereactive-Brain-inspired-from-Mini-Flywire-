// Builds the single-file M13 review bundle: REVIEW_PACKAGE.md (the cover), then every file of the package verbatim
// with its SHA-256. Written 2026-11-18 for the review package; it reads files and git metadata only and changes nothing
// else. Run from the repository root:  node experiments/m13_generalization/review/build_bundle.mjs
// Hashes: "raw" is the SHA-256 of the bytes on disk; "content" reads CRLF as LF (the PINS.json convention, because
// cognitive/ has no exact-bytes rule and a checkout may convert line endings). Files are reproduced with LF endings.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';

const M = 'experiments/m13_generalization';
const OUT = `${M}/review/M13_REVIEW_BUNDLE.md`;
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
const git = (...a) => execFileSync('git', a, { encoding: 'utf8', maxBuffer: 1 << 26 }).replace(/\r\n/g, '\n');
const lang = (p) => (p.endsWith('.md') ? 'markdown' : p.endsWith('.json') ? 'json' : p.endsWith('.mjs') ? 'js' : p.endsWith('.ps1') ? 'powershell' : p.endsWith('.csv') ? 'csv' : 'text');
const fenceFor = (text) => '`'.repeat(Math.max(4, ...[...text.matchAll(/`+/g)].map((m) => m[0].length + 1)));

const pins = JSON.parse(fs.readFileSync(`${M}/PINS.json`, 'utf8')).files;
const pinned = Object.keys(pins);
const implementation = ['worlds_modular.mjs', 'structure.mjs', 'make_bank.mjs', 'measures.mjs', 'm13_lib.mjs', 'pins.mjs', 'run_m13.mjs', 'structure.json'].map((f) => `${M}/${f}`);
const bank = `${M}/graph_bank.json`;
const dependencies = pinned.filter((p) => !implementation.includes(p) && p !== bank).sort();

const APPENDICES = [
  ['A', 'Frozen specification and its recorded hashes', [`${M}/SPEC.md`, `${M}/SPEC.sha256`, `${M}/PINS.json`]],
  ['B', 'The approved proposal and its no-agent inputs', [`${M}/PROPOSAL.md`, `${M}/proposal_inputs/structure_survey.mjs`, `${M}/proposal_inputs/structure_survey.out`, `${M}/proposal_inputs/power_inputs.mjs`, `${M}/proposal_inputs/power_inputs.out`]],
  ['C', 'M13 implementation (generator, structure, measures, library, pins, driver)', implementation],
  ['D', 'All other pinned dependencies (agents, models, planner, task, environment, statistics, recorder, test runner)', dependencies],
  ['E', 'Regression tests for M13 and the adopted agent (run by the driver through scripts/test.mjs; not pinned)', ['cognitive/tests/test_m13_generalization.mjs', 'cognitive/tests/test_adopted_agent.mjs']],
  ['F', 'Sample size and power (no agent)', [`${M}/power/power_m13.mjs`, `${M}/power/power_m13.out`, `${M}/power/power_m13.json`]],
  ['G', 'Run provenance', [`${M}/results/run/run_m13_awake.ps1`, `${M}/results/run/hold_awake_until.ps1`, `${M}/results/run/m13_run.log`, `${M}/results/run/m13_run.stdout`, `${M}/results/run/m13_run.stderr`, `${M}/results/run/m13_power_events.txt`, `${M}/results/SHA256SUMS`]],
  ['H', 'Independent check, written before the result', [`${M}/results/check/verify_m13.mjs`, `${M}/results/check/verify_m13.out`]],
  ['I', 'The results record', [`${M}/RESULTS.md`]],
  ['J', 'Descriptive analyses written after the result (RESULTS §8–§9)', [`${M}/results/check/crossing_split.mjs`, `${M}/results/check/crossing_split.out`, `${M}/results/check/trace_summary.mjs`, `${M}/results/check/trace_summary.out`]],
  ['K', 'Review-package supplements, written after the result', [`${M}/review/check_measures_from_traces.mjs`, `${M}/review/check_measures_from_traces.out`, `${M}/review/per_label.mjs`, `${M}/review/per_label.csv`, `${M}/review/build_bundle.mjs`]],
  ['N', 'The frozen graph bank (pinned data; regenerated and compared by make_bank.mjs --check)', [bank]],
];

const files = APPENDICES.flatMap(([, , fs_]) => fs_);
const missing = files.filter((f) => !fs.existsSync(f));
if (missing.length) throw new Error(`missing: ${missing.join(', ')}`);
// Files under experiments/m13_generalization are stored byte-exact (-text), so their raw bytes are the same in every
// checkout; elsewhere only the content (CRLF read as LF) is checkout-independent, so only it is reported.
const info = (p) => {
  const raw = fs.readFileSync(p), text = raw.toString('utf8').replace(/\r\n/g, '\n'), exact = p.startsWith(`${M}/`);
  const content = sha(Buffer.from(text, 'utf8'));
  return { p, bytes: exact ? raw.length : Buffer.byteLength(text, 'utf8'), raw: exact ? sha(raw) : content, content, text, lines: text.split('\n').length - (text.endsWith('\n') ? 1 : 0) };
};
const I = new Map([`${M}/review/REVIEW_PACKAGE.md`, ...files].map((p) => [p, info(p)]));
for (const p of pinned) if (pins[p] !== I.get(p).content) throw new Error(`${p} does not match PINS.json`);

const parts = [];
parts.push(I.get(`${M}/review/REVIEW_PACKAGE.md`).text.trimEnd(), '', '---', '', '# Bundle contents');
parts.push('', `Generated by \`${M}/review/build_bundle.mjs\` from the results commit \`b9a05e0\` plus the review folder added on top of it. Rebuilding it at the package commit reproduces the same content.`);
parts.push('Every file below is reproduced verbatim, with LF line endings. "content" is its SHA-256 with CRLF read as LF; for every pinned file it equals `PINS.json`. "raw" is the SHA-256 of the stored bytes, shown only where it differs: the two run files PowerShell wrote with CRLF endings, whose raw hash is the one in `results/SHA256SUMS`. Files under `experiments/m13_generalization/` are stored byte-exact; elsewhere a checkout may convert line endings, so only the content hash is given. "Bytes" is the stored size for files under `experiments/m13_generalization/`, and the LF content size elsewhere.');
parts.push('', '| Appendix | File | Bytes | Lines | SHA-256 (content) |', '|---|---|---|---|---|');
{ const x = I.get(`${M}/review/REVIEW_PACKAGE.md`); parts.push(`| cover | \`${x.p}\` | ${x.bytes} | ${x.lines} | \`${x.content}\` |`); }
for (const [L, , fs_] of APPENDICES) for (const p of fs_) { const x = I.get(p); parts.push(`| ${L} | \`${p}\` | ${x.bytes} | ${x.lines} | \`${x.content}\`${x.raw !== x.content ? ` (raw \`${x.raw}\`)` : ''} |`); }
parts.push('', 'Generated sections, not files: G2 (the M13 commit history), G3 (the raw result without `rows` and `traces`, and one example row), L (the PROJECT_STATE changes).');

const section = (p, title) => {
  const x = I.get(p), fence = fenceFor(x.text);
  return [``, `### ${title ?? p}`, ``, `File: \`${p}\` · SHA-256 (content) \`${x.content}\`${x.raw !== x.content ? ` · raw \`${x.raw}\`` : ''} · ${x.bytes} bytes · ${x.lines} lines`, ``, `${fence}${lang(p)}`, x.text.endsWith('\n') ? x.text.slice(0, -1) : x.text, fence].join('\n');
};

for (const [L, title, fs_] of APPENDICES) {
  parts.push('', '---', '', `## Appendix ${L}. ${title}`);
  if (L === 'D') parts.push('', `${fs_.length} files. Together with appendix C, the graph bank (N) and the two scripts the driver runs, they are the ${pinned.length} files of \`PINS.json\`.`);
  for (const p of fs_) parts.push(section(p));
  if (L === 'G') {
    const log = git('log', '--format=%H %ad %s', '--date=iso-strict', '728dd71..b9a05e0');
    const stats = ['6381450', 'b48453e', '8619d71', 'b9a05e0'].map((c) => git('show', '--stat=160', '--format=commit %H%n%s%n', c)).join('\n');
    const g2 = `${log}\n${stats}`;
    parts.push('', '### G2. The M13 commit history (generated: `git log 728dd71..b9a05e0` and `git show --stat` of each commit)', '', `${fenceFor(g2)}text`, g2.trimEnd(), fenceFor(g2));
    const resultPath = `${M}/results/m13_result.json`, raw = fs.readFileSync(resultPath), j = JSON.parse(raw);
    const { rows, traces, ...rest } = j;
    const example = rows.find((r) => r.world === `m13|modular|0` && r.family === 'OFTEN' && r.arm === 'BELIEF');
    const g3 = JSON.stringify(rest, null, 1);
    parts.push('', `### G3. The raw result, every top-level field except \`rows\` and \`traces\` (generated)`, '',
      `File: \`${resultPath}\` · SHA-256 \`${sha(raw)}\` · ${raw.length} bytes. It holds ${rows.length} rows (run A: 165 labels × 3 families × 4 arms) and ${traces.length} traces (labels 0–2, all families, BELIEF and MBVI3), which are too large to reproduce here; \`review/per_label.csv\` (appendix K) holds every per-label number the criteria and the attribution use. Field order and values below are exactly the file's.`,
      '', `${fenceFor(g3)}json`, g3, fenceFor(g3),
      '', 'One row, verbatim (`m13|modular|0`, OFTEN, BELIEF), to show the row structure:', '', '````json', JSON.stringify(example, null, 1), '````');
  }
  if (L === 'K') {
    const d = git('diff', '728dd71', 'b9a05e0', '--', 'docs/engineering/PROJECT_STATE.md');
    parts.push('', '---', '', '## Appendix L. PROJECT_STATE changes for M13 (generated: `git diff 728dd71 b9a05e0 -- docs/engineering/PROJECT_STATE.md`)', '', `${fenceFor(d)}diff`, d.trimEnd(), fenceFor(d));
  }
}
fs.writeFileSync(OUT, parts.join('\n') + '\n');
const out = fs.readFileSync(OUT);
console.log(`${OUT}: ${out.length} bytes, SHA-256 ${sha(out)}; ${files.length} files reproduced`);
